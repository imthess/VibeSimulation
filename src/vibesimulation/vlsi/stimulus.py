"""A testbench written for a circuit that has none: a clock, a reset pulse and random (or counting) inputs.

The text is ordinary Verilog, so the result can be run like any testbench or pasted into the Testbench tab and changed.
"""
import re

CLOCKS = re.compile(r"^(clk|clock|clk_i|ck|clkin)\d*$", re.I)
RESETS = re.compile(r"^(rst|reset|rstn|rst_n|reset_n|resetn|rst_b|clr|clear|arst|arst_n|areset|nrst|nreset)$", re.I)


def _active_low(name):
    n = name.lower()
    return bool(re.search(r"(rst|reset|clr|clear)_?n$", n) or re.search(r"_(b|low|l)$", n) or n.startswith(("n_", "nrst", "nreset")))


def find_clock(circ):
    for p in circ.inputs:
        if p.width == 1 and CLOCKS.match(p.name): return p.name
    for c in circ.components:                       # an input that drives a clock pin
        if getattr(c, "sequential", False):
            s = c.ins.get("Clk")
            if s is not None and any(p.name == s and p.width == 1 for p in circ.inputs): return s
    return None


def find_reset(circ, clock):
    for p in circ.inputs:
        if p.width == 1 and p.name != clock and RESETS.match(p.name): return p.name
    return None


def rng(w): return f"[{w - 1}:0] " if w > 1 else ""


def generate_testbench(name, circ, cycles=64, period=10, mode="random"):
    """Verilog for a module `vs_auto_tb` that exercises module `name` (whose pins are those of `circ`)."""
    clk, rst = find_clock(circ), None
    rst = find_reset(circ, clk)
    ins = list(circ.inputs); outs = list(circ.outputs)
    data = [p for p in ins if p.name not in (clk, rst)]
    L = ["// Generated by VibeSimulation: a clock, a reset pulse and " + ("counting" if mode == "count" else "random") + " inputs. Edit it freely.", "module vs_auto_tb;"]
    for p in ins: L.append(f"  reg {rng(p.width)}{p.name};")
    for p in outs: L.append(f"  wire {rng(p.width)}{p.name};")
    L.append("  integer i;")
    pins = ", ".join(f".{p.name}({p.name})" for p in ins + outs)
    L.append(f"  {name} dut ({pins});")
    if clk: L.append(f"  always #{period // 2} {clk} = ~{clk};")
    L.append("  initial begin")
    if clk: L.append(f"    {clk} = 0;")
    low = rst is not None and _active_low(rst)
    if rst: L.append(f"    {rst} = {0 if low else 1};")
    for p in data: L.append(f"    {p.name} = 0;")
    if clk and rst:
        L.append(f"    repeat (2) @(negedge {clk});"); L.append(f"    {rst} = {1 if low else 0};")
    step = f"@(negedge {clk})" if clk else f"#{period}"
    total = sum(p.width for p in data)
    L.append(f"    for (i = 0; i < {cycles}; i = i + 1) begin")
    L.append(f"      {step};")
    if mode == "count" and total <= 30 and data:
        pos = 0
        for p in data: L.append(f"      {p.name} = i[{pos + p.width - 1}:{pos}];" if p.width > 1 or pos else f"      {p.name} = i[{pos}];"); pos += p.width
    else:
        for p in data: L.append(f"      {p.name} = $random;")
    L.append("    end")
    L.append(f"    {step};")
    L.append("    $finish;"); L.append("  end"); L.append("endmodule")
    return "\n".join(L) + "\n"
