"""Dev tool: ask the real Logisim for each component's default settings and write src/vibesimulation/imports/logisim_defaults.py."""
import sys, subprocess, re, itertools, json
sys.path.insert(0, "src")
from vibesimulation.components import load_all, ComponentRegistry as R
from vibesimulation.export.logisim import HEADER, FOOTER, LIB
load_all()
classes = {id(c): c for c in R._classes.values()}.values()
skip = {"Splitter", "Combiner", "Pin"}
def dump(items):
    body = "".join(f'    <comp lib="{l}" loc="({200+i*200},300)" name="{n}">\n' + "".join(f'      <a name="{k}" val="{v}"/>\n' for k, v in a.items()) + "    </comp>\n" for i, (l, n, a) in enumerate(items))
    open("/tmp/gd.circ", "w").write(HEADER + body + FOOTER)
    out = subprocess.run(["java", "-Djava.awt.headless=true", "-cp", "dev/logisim.jar:dev", "Dump", "/tmp/gd.circ"], capture_output=True, text=True).stdout
    res = []
    for l in out.splitlines():
        if l.startswith("COMP"): res.append(dict(re.findall(r"\[(\w+)=([^\]]*)\]", l)))
    return res
cl = [c for c in classes if c.type_name not in skip and c.logisim_name]
cl = sorted({c.logisim_name: c for c in cl}.values(), key=lambda c: c.logisim_name)   # one per logisim name
# 1) printed defaults
printed = dump([(LIB[c.library], c.logisim_name, {}) for c in cl])
# 2) for choice attrs: file-form value -> printed form
table = {}
for c, pr in zip(cl, printed):
    keys = set(); forms = []
    base = c("x")
    variants = [base]
    for a in c.attrs_spec:
        if a.kind == "choice":
            for ch in a.choices:
                v = c("x"); v.set_attr(a.name, ch); variants.append(v)
        elif a.kind == "bool":
            v = c("x"); v.set_attr(a.name, not a.default); variants.append(v)
    las = [dict((k, str(x)) for k, x in v.logisim_attrs().items()) for v in variants]
    for la in las: keys |= set(la)
    printed_v = dump([(LIB[c.library], c.logisim_name, la) for la in las])
    file2print = {}
    for la, p in zip(las, printed_v):
        for k, x in la.items(): file2print.setdefault(k, {})[x] = p.get(k)
    d = {}
    for k in sorted(keys):
        pv = pr.get(k)
        m = file2print.get(k, {})
        inv = {p: f for f, p in m.items() if p is not None}
        d[k] = inv.get(pv, pv)
    table[c.logisim_name] = d
with open("src/vibesimulation/imports/logisim_defaults.py", "w") as f:
    f.write('"""Default settings of Logisim components (as written in .circ files), measured from Logisim-evolution 3.8.0.\nGenerated by dev/gen_defaults.py."""\n\nDEFAULTS = ')
    f.write(json.dumps(table, indent=1, sort_keys=True).replace("true", "True").replace("false", "False").replace("null", "None") if False else repr(table).replace("}, '", "},\n '"))
    f.write("\n")
print(len(table)); [print(k, v) for k, v in table.items()]
